  const SUPPORTED = ["en", "es", "fr", "zh-Hans", "zh-Hant", "ja"];
  const HTML_LANG = {
    en: "en",
    es: "es",
    fr: "fr",
    "zh-Hans": "zh-CN",
    "zh-Hant": "zh-TW",
    ja: "ja",
  };
  let lang = "en";

  function normalize(raw) {
    if (!raw) return "en";
    const v = String(raw).replace("_", "-");
    if (SUPPORTED.indexOf(v) !== -1) return v;
    if (v === "zh" || v === "zh-CN" || v === "zh-SG" || v === "zh-Hans-CN") return "zh-Hans";
    if (v === "zh-TW" || v === "zh-HK" || v === "zh-MO" || v === "zh-Hant-TW" || v === "zh-Hant-HK") return "zh-Hant";
    const base = v.slice(0, 2).toLowerCase();
    if (base === "es") return "es";
    if (base === "fr") return "fr";
    if (base === "zh") return "zh-Hans";
    if (base === "ja") return "ja";
    if (base === "en") return "en";
    return "en";
  }

  function detect() {
    try {
      const saved = localStorage.getItem("pp_lang");
      if (saved) return normalize(saved);
    } catch (e) {}
    const nav = (navigator.languages && navigator.languages[0]) || navigator.language || "en";
    return normalize(nav);
  }

  function t(key, vars) {
    let s =
      (DICT[lang] && DICT[lang][key]) ||
      (DICT.en && DICT.en[key]) ||
      (DICT["zh-Hans"] && DICT["zh-Hans"][key]) ||
      key;
    if (vars) {
      for (const k of Object.keys(vars)) {
        s = s.replace(new RegExp("\\{" + k + "\\}", "g"), vars[k]);
      }
    }
    return s;
  }

  function applyStatic() {
    document.querySelectorAll("[data-i18n]").forEach((el) => {
      el.textContent = t(el.getAttribute("data-i18n"));
    });
    document.querySelectorAll("[data-i18n-aria]").forEach((el) => {
      el.setAttribute("aria-label", t(el.getAttribute("data-i18n-aria")));
    });
    document.title = t("app.title");
  }

  function updateButtons() {
    document.querySelectorAll(".lang-btn").forEach((btn) => {
      btn.classList.toggle("active", btn.getAttribute("data-lang") === lang);
      btn.setAttribute("aria-pressed", btn.getAttribute("data-lang") === lang ? "true" : "false");
    });
  }

  function setLang(next) {
    lang = normalize(next);
    try {
      localStorage.setItem("pp_lang", lang);
    } catch (e) {}
    document.documentElement.lang = HTML_LANG[lang] || "en";
    applyStatic();
    updateButtons();
    if (typeof window.onLangChange === "function") window.onLangChange();
  }

